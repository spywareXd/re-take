"""Generate *_v2.py copies of the evaluation scripts that read pairs_v2.csv and write ONLY to results_v2/.
The originals are never modified. Caches are COPIED into results_v2/ (few-shot answers are left out, see report)."""
import json
import shutil
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "results_v2"
OUT.mkdir(exist_ok=True)
(OUT / "veto").mkdir(exist_ok=True)

SUBS = [('HERE / "pairs_v1.csv"', 'HERE / "pairs_v2.csv"'), ('HERE / "results"', 'HERE / "results_v2"')]
EXTRA = {   # per-script relaxations of asserts that hard-code the v1 row counts
    "adjudication_compare": [("assert len(df) == len(base) == 3570", "assert len(df) == len(base)")],
    "veto_test": [("assert len(df) == 3570", "assert len(df) > 3000"),
                  ('assert len(SET) == 333 and int(SET.label.sum()) == 303, "pair set differs from the pre-registration"',
                   'print("v2 pair set:", len(SET), "pairs,", int(SET.label.sum()), "retakes")')],
}
for name in ["baselines", "logreg", "gbm_errors", "train_cross_encoder", "combine", "adjudication_compare", "veto_test"]:
    src = (HERE / f"{name}.py").read_text(encoding="utf-8")
    for a, b in SUBS + EXTRA.get(name, []):
        if a in src:
            src = src.replace(a, b)
    assert "pairs_v1.csv\")" not in src.replace('"pairs_v1.csv", dtype', "X") or True
    header = f'"""V2 COPY of {name}.py: reads data/training/pairs_v2.csv (corrected labels) and writes only to results_v2/. Generated by make_v2_scripts.py; do not edit."""\n'
    (HERE / f"{name}_v2.py").write_text(header + src, encoding="utf-8")
    print("wrote", f"{name}_v2.py")

# caches: copy (never modify the originals); drop few-shot answers (fold-1 example label changed)
lines = []
for line in (HERE / "results" / "gemini_cache.jsonl").read_text(encoding="utf-8").splitlines():
    if json.loads(line)["variant"].startswith("few_v1"):
        continue
    lines.append(line)
(OUT / "gemini_cache.jsonl").write_text("\n".join(lines) + "\n", encoding="utf-8")
shutil.copy2(HERE / "results" / "fewshot_examples.json", OUT / "fewshot_examples.json")
shutil.copy2(HERE / "results" / "veto" / "veto_cache.jsonl", OUT / "veto" / "veto_cache.jsonl")
shutil.copy2(HERE / "results" / "veto" / "preregistration.md", OUT / "veto" / "preregistration.md")
print("caches copied; gemini cache lines kept:", len(lines))
